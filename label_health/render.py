"""Self-contained HTML and PDF report rendering."""
from __future__ import annotations
from datetime import date
from html import escape
from typing import Any
from html.parser import HTMLParser
from io import BytesIO


def _safe(value: Any) -> str:
    return escape(str(value), quote=True)


def _percent(value: float | None) -> str:
    return f"{value:.1%}" if value is not None else "Insufficient data"


def render_html_report(report: dict[str, Any]) -> str:
    colors = {"GREEN": "#22c55e", "AMBER": "#f59e0b", "RED": "#ef4444"}
    overall_text = _percent(report["overall_accuracy"])
    category_rows = "".join(
        f'<tr data-risk="{_safe(row["risk_level"])}"><td>{_safe(row["category"])}</td><td>{_percent(row["accuracy"])}</td>'
        f'<td>{row["verified_count"]}</td><td style="color:{colors.get(row["risk_level"], "#111827")}">'
        f'{_safe(row["risk_level"])}</td><td>{_safe(row["conservation_phase"])}</td></tr>'
        for row in report["category_risks"]
    )
    inversion = report.get("inversion")
    inversion_card = (f'<div class="alert"><strong>Signal-Confidence Inversion</strong><p>'
                      f'Your annotators trust {_safe(inversion["trusted_factor"])} most. '
                      f'But {_safe(inversion["actual_signal_factor"])} is more predictive.</p></div>') if inversion else ""
    profiles = report.get("annotator_profiles")
    profile_rows = "".join(
        f'<tr><td>{_safe(p["annotator_id"])}</td><td>{p["overall_accuracy"]:.1%}</td>'
        f'<td>{_safe(p["strongest"])}</td><td>{_safe(p["weakest"])}</td></tr>' for p in (profiles or [])
    )
    profile_section = (f'<h3>Annotator fingerprints</h3><table><tr><th>Annotator</th><th>Accuracy</th>'
                       f'<th>Strongest</th><th>Weakest</th></tr>{profile_rows}</table>') if profiles is not None else ""
    silent = "".join(
        f'<li>Category {_safe(row["category"])} has only {row["verified_count"]} verified labels '
        f'— accuracy could be anywhere from 0% to 100%.</li>' for row in report["silent_risks"]
    )
    cost = report["cost_projection"]
    cost_text = (f'At current error rates, your next 10,000 labels will cost an estimated '
                 f'<strong>${cost["total_projected_cost"]:,.2f}</strong>. '
                 f'{cost["labels_needing_reverification"]} labels need reverification. '
                 f'{_safe(cost["confidence"])}.') if cost is not None else "Insufficient data"
    message = f'<p>{_safe(report["message"])}</p>' if report.get("message") else ""
    return f'''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Label Health Report</title><style>
body{{font-family:Arial,Helvetica,sans-serif;background:#f8fafc;color:#111827;margin:0;padding:2rem}}
main{{max-width:900px;margin:auto}}section{{background:white;padding:1.5rem;margin:1rem 0;border-radius:12px;box-shadow:0 1px 4px #ddd}}
table{{width:100%;border-collapse:collapse}}td,th{{padding:.7rem;text-align:left;border-bottom:1px solid #e5e7eb}}
.alert{{background:#fff7ed;border-left:5px solid #f59e0b;padding:1rem}}.metric{{font-size:2rem;font-weight:700}}
@media(max-width:600px){{body{{padding:.5rem}}section{{padding:.8rem}}table{{font-size:.8rem}}}}
</style></head><body><main><h1>Label Health Report</h1>
<section><h2>What you asked for</h2><p>Overall accuracy</p><div class="metric">{overall_text}</div>{message}
<h3>Category risk</h3><label>Filter risk <select id="risk-filter" onchange="filterRisk()"><option>All</option><option>RED</option><option>AMBER</option><option>GREEN</option></select></label>
<table id="category-table"><tr><th>Category</th><th>Accuracy</th><th>Verified</th><th>Risk</th><th>Conservation</th></tr>{category_rows}</table></section>
<section><h2>What you didn't know to ask</h2>{inversion_card}{profile_section}<h3>Silent risks</h3><ul>{silent}</ul></section>
<section><h2>Projected cost of inaction</h2><p>{cost_text}</p></section>
<footer>Generated by RGI Data Label Judgment · {date.today().isoformat()}<p>Want this running live on every batch? rgi.dakshineshwari.net/labeling/</p></footer>
</main><script>function filterRisk(){{const selected=document.getElementById('risk-filter').value;
document.querySelectorAll('#category-table tr[data-risk]').forEach(row=>{{row.hidden=selected!=='All'&&row.dataset.risk!==selected}})}}</script></body></html>'''


class _PlainText(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.parts: list[str] = []
        self.hidden_depth = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag in {"style", "script"}:
            self.hidden_depth += 1

    def handle_endtag(self, tag: str) -> None:
        if tag in {"style", "script"} and self.hidden_depth:
            self.hidden_depth -= 1

    def handle_data(self, data: str) -> None:
        if not self.hidden_depth and data.strip():
            self.parts.append(data.strip())


def render_pdf(html: str) -> bytes:
    """Use WeasyPrint where native libraries exist; retain PDF output elsewhere."""
    try:
        from weasyprint import HTML  # type: ignore[import]
        result = HTML(string=html).write_pdf()
        if result is None:
            raise RuntimeError("PDF renderer produced no output")
        return result
    except OSError:
        from reportlab.pdfgen import canvas  # type: ignore[import]
        parser = _PlainText()
        parser.feed(html)
        output = BytesIO()
        document = canvas.Canvas(output, pagesize=(595, 842))
        y = 800
        for part in parser.parts:
            for start in range(0, len(part), 90):
                if y < 45:
                    document.showPage()
                    y = 800
                document.drawString(36, y, part[start:start + 90])
                y -= 18
        document.save()
        return output.getvalue()
